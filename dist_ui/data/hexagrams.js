/**
 * 三爻布尔值 → 八卦索引的映射表。
 * 输入三位 [初爻, 中爻, 上爻]（true=阳），通过二进制加权(4,2,1)后查表。
 */
const BIT_TO_TRI_IDX = [7, 3, 5, 1, 6, 2, 4, 0];
/**
 * 将三爻布尔数组转换为八卦索引。
 * @param a - [初爻, 中爻, 上爻]，true 表示阳爻
 * @returns 八卦索引（0-7）
 */
export function bitsToTrigramIdx(a) {
    const bits = (a[0] ? 4 : 0) + (a[1] ? 2 : 0) + (a[2] ? 1 : 0);
    return BIT_TO_TRI_IDX[bits] ?? 0;
}
/**
 * 按卦序索引获取六十四卦详细信息。
 * @param index - 卦序（1-64）
 * @returns 卦象数据（含名称、宫位、世应、爻线等）
 */
export function getHexagramByIndex(index) {
    if (index < 1 || index > 64)
        throw new Error('index out of range');
    const i = index - 1;
    const bits = RAW_LINES[i];
    // 将字符串转为布尔数组，注意位序：bits[5-j] 对应第 (j+1) 爻（自下而上）
    const lines = Array.from({ length: 6 }, (_, j) => bits[5 - j] === '1');
    const upperIdx = bitsToTrigramIdx([bits[0] === '1', bits[1] === '1', bits[2] === '1']);
    const lowerIdx = bitsToTrigramIdx([bits[3] === '1', bits[4] === '1', bits[5] === '1']);
    const [shi, ying] = (RAW_SHI_YING[i] || '6-3').split('-').map(Number);
    return {
        index,
        name: RAW_SHORT[i],
        fullName: RAW_FULL[i],
        palace: RAW_PALACE[i],
        upper: upperIdx,
        lower: lowerIdx,
        element: TRIGRAM_ELEMENT[upperIdx],
        nature: (TRIGRAM_NATURE[upperIdx] || '') + (TRIGRAM_NATURE[lowerIdx] || ''),
        shiPosition: shi,
        yingPosition: ying,
        lines,
    };
}
/**
 * 根据上卦、下卦索引查找六十四卦序号。
 * @param upper - 上卦索引（0-7）
 * @param lower - 下卦索引（0-7）
 * @returns 卦序（1-64）
 */
export function findHexagramByTrigrams(upper, lower) {
    const target = (TRIGRAM_BITS[upper] || '') + (TRIGRAM_BITS[lower] || '');
    return RAW_LINES.indexOf(target) + 1;
}
/**
 * 根据动爻位置翻转指定爻线，生成变卦爻线。
 * @param lines - 原始爻线（自下而上 6 位）
 * @param moving - 动爻位置数组（1-6）
 * @returns 变卦后的爻线数组
 */
export function changeLines(lines, moving) {
    return lines.map((v, i) => (moving.includes(i + 1) ? !v : v));
}
