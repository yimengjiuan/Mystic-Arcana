/**
 * 查询十神关系。
 * @param dayGan - 日柱天干
 * @param otherGan - 待查天干
 * @returns 十神名称
 */
export function shiShenOf(dayGan: string, otherGan: string): string {
  return SHI_SHEN[dayGan]?.[otherGan] || '';
}

