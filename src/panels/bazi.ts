/**
 * 构建四柱详情面板。
 * @param bazi - 四柱数据
 * @returns 柱详情数组及命局概述
 */
export function buildBaziPanel(bazi: Bazi): { pillars: PillarDetail[]; summary: string } {
  const dayGan = bazi.day.gan;
  // 遍历年月日时四柱，计算藏干十神与纳音
  const pillars = [bazi.year, bazi.month, bazi.day, bazi.hour].map(p => ({
    gz: p,
    canggan: parseCanggan(p.zhi).map(g => ({ gan: g, shiShen: shiShenOf(dayGan, g) })),
    nayin: NAYIN_TABLE[p.ganzhi] || '',
  }));

  // 命局概述：检测桃花（子午卯酉）
  let summary = `日主${dayGan}，生于${bazi.month.ganzhi}月。`;
  if (['子', '午', '卯', '酉'].some(z => bazi.month.zhi === z || bazi.day.zhi === z)) {
    summary += '四柱有桃花，需防感情纠葛。';
  } else {
    summary += '命局平和，宜稳中求进。';
  }

  return { pillars, summary };
}
